import { after, NextResponse, type NextRequest } from "next/server";
import { z } from "zod";
import {
  parsePageContext,
  reasoningEffortSchema,
} from "@/lib/chat/contracts";
import {
  authenticate,
  beginTurn,
} from "@/lib/chat/server/conversation-service";
import { getLiveTurn } from "@/lib/chat/server/turn-bus";
import { startTurn, turnSettled } from "@/lib/chat/server/turn-runner";
import { streamLiveTurn, streamPersistedTurn } from "@/lib/chat/server/turn-stream";

// Generation outlives the browser request; give the platform room to finish it.
export const maxDuration = 300;

const startTurnSchema = z.object({
  sessionId: z.string().uuid(),
  turnId: z.string().uuid(),
  mode: z.enum(["new", "edit", "retry"]),
  content: z.string().max(100_000),
  targetMessageId: z.string().uuid().nullish(),
  model: z.string().max(100).nullish(),
  settings: z
    .object({
      reasoningEffort: reasoningEffortSchema.nullish(),
      webSearchEnabled: z.boolean(),
    })
    .nullish(),
  attachments: z
    .array(
      z.object({
        name: z.string().max(500),
        mime_type: z.string().max(200),
        size: z.number().int().nonnegative(),
        storage_path: z.string().max(1000),
        width: z.number().int().nullish(),
        height: z.number().int().nullish(),
      })
    )
    .max(20)
    .default([]),
  context: z.unknown().optional(),
  request: z
    .object({
      clientTz: z.string().max(100).optional(),
      clientUtcOffset: z.string().max(10).optional(),
      clientNowIso: z.string().max(40).optional(),
      clientPath: z.string().max(2000).optional(),
    })
    .default({}),
});

/**
 * Begin a turn and stream it. The reply is generated by the server, so the
 * response stream can close (tab closed, navigation) without stopping it.
 */
export async function POST(request: NextRequest) {
  const auth = await authenticate(request.headers.get("x-chat-account-id"));
  if (auth.error !== undefined)
    return NextResponse.json(
      { message: auth.error },
      { status: auth.error === "Not authenticated" ? 401 : 409 }
    );

  const body = startTurnSchema.safeParse(await request.json().catch(() => null));
  if (!body.success)
    return NextResponse.json(
      { message: z.prettifyError(body.error) },
      { status: 400 }
    );
  const input = body.data;
  const context = parsePageContext(input.context);

  const begun = await beginTurn(auth.data, {
    sessionId: input.sessionId,
    turnId: input.turnId,
    mode: input.mode,
    content: input.content,
    targetMessageId: input.targetMessageId,
    model: input.model,
    settings: input.settings,
    attachments: input.attachments,
    context,
    request: { ...input.request, appBaseUrl: request.nextUrl.origin },
  });
  if (begun.error !== undefined)
    return NextResponse.json({ message: begun.error }, { status: 409 });
  const turn = begun.data;
  const first = { type: "turn" as const, turn };

  // A resend of a turn that already began attaches instead of starting twice.
  if (turn.existing) {
    const running = getLiveTurn(turn.turnId, auth.data.userId);
    return running
      ? streamLiveTurn(running, first)
      : streamPersistedTurn(auth.data, turn.turnId, first);
  }

  const live = startTurn({
    auth: auth.data,
    turn: {
      sessionId: turn.sessionId,
      turnId: turn.turnId,
      assistantMessageId: turn.assistantMessageId,
    },
    model: turn.model,
    settings: turn.settings,
    request: { ...input.request, appBaseUrl: request.nextUrl.origin },
    context,
    path: [...turn.history, turn.userMessage],
  });
  if (!live) return streamPersistedTurn(auth.data, turn.turnId, first);
  after(() => turnSettled(live));
  return streamLiveTurn(live, first);
}
